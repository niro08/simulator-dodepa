type Vars = Record<string, string | number | undefined>

/** Подстановка {ключ} → значение; суммы форматируются, вещи — с эмодзи. Неизвестные ключи остаются как есть. */
export function fillPlaceholders(template: string, vars: Vars): string {
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => {
    const v = vars[key]
    if (v === undefined) return whole
    if (key === 'item' && typeof v === 'string') return ITEM_NAMES[v as ItemId] ?? v
    if (key === 'net' && typeof v === 'number') return signed(v).replace(/\d+/, (d) => money(Number(d)))
    return typeof v === 'number' ? money(v) : v
  })
}

/** Карточка сна для экрана: тексты с подстановками (PendingEventView.vars). */
export function formatSleepEventCard(view: { eventId: string; vars?: Vars }): {
  speaker: string
  text: string
  options: [string, string]
} | null {
  const t = SLEEP_EVENT_TEXTS[view.eventId]
  if (!t) return null
  const vars = view.vars ?? {}
  return {
    speaker: t.speaker,
    text: fillPlaceholders(t.text, vars),
    options: [fillPlaceholders(t.options[0], vars), fillPlaceholders(t.options[1], vars)]
  }
}

